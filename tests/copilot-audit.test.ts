import { executionErrorAudit } from '../copilot-sql';
import { dbhubOutcome } from '../copilot-mcp';
let fail = 0;
const ok = (name: string, cond: boolean) => { console.log(cond ? 'PASS' : 'FAIL', name); if (!cond) fail++; };
const a = executionErrorAudit('crm', 'SELECT 1', "User 'copilot_ro' has exceeded the 'max_user_connections'", 12);
ok('builtin execution error -> allowed=false', a.allowed === false);
ok('builtin execution error keeps message', a.reason!.startsWith('execution error: ') && a.reason!.includes('max_user_connections'));
ok('builtin execution error rows=null', a.rows === null && a.ms === 12);
const denied = { success: false, error: "SELECT command denied to user 'copilot_dbhub' for column 'authority'", code: 'EXECUTION_ERROR' };
const o1 = dbhubOutcome({ isError: true }, JSON.stringify(denied), denied);
ok('dbhub isError -> failed', o1.failed && o1.error.includes('command denied'));
const ro = { success: false, error: 'Read-only mode is enabled', code: 'READONLY_VIOLATION' };
ok('dbhub success:false -> failed', dbhubOutcome({}, JSON.stringify(ro), ro).failed);
const good = { success: true, data: { statements: [{ sql: 'x', rows: [{ a: 1 }, { a: 2 }], count: 2 }] } };
const o3 = dbhubOutcome({}, JSON.stringify(good), good);
ok('dbhub success -> rows', !o3.failed && o3.rows.length === 2 && o3.error === '');
ok('dbhub plain-text error', dbhubOutcome({ isError: true }, 'boom', 'boom').error === 'boom');
const e2 = executionErrorAudit('dbhub', 'trainee_count({})', 'dbhub error: fetch failed', 5);
ok('dbhub transport error -> allowed=false', e2.allowed === false && e2.db === 'dbhub');
console.log(fail ? `${fail} failed` : 'all passed'); process.exit(fail ? 1 : 0);
